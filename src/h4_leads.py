"""H4 with the 8 x 8 lead-space transform (analysis plan 5.2 sensitivity estimator; docs/decisions.md
item 29). Label-free; on HEEDB-MGH and HEEDB-EUH, both descriptive.

- SR loop: the 8-lead SR template (I, II, V1-V6) from QRS onset to offset, resampled to 100 points.
- A8 = (X2 X1' + λI)(X1 X1' + λI)^-1, λ = κ8 tr(X1 X1')/8 (ridge to identity, as `h4.fit_a`).
- d: 1 - cosine similarity of the 8-lead PVC windows (-10 to +180 ms), shift up to ±10 ms, both
  directions averaged (as `h4`, in lead space). κ8 from the grid of `h4.KAPPAS` by the median d_own
  of the MGH primary stratum; a check beyond the grid is reported.
- Clinical units: as `src.h4_clinical`, with the corrected PVC L' = A8 L.

    python -m src.h4_leads   -> docs/wp2_h4_leads.md
"""
import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

from src.config import DOCS
from src.h4 import KAPPAS, LAG, LOOP_N, OUT, WIN
from src.h4_clinical import med, measures, share

STRATUM = "primary (<= 365 days)"


def sr_loop8(t):
    v = t["sr"][:, t["sr_on"]:t["sr_off"] + 1]
    x = np.linspace(0, v.shape[1] - 1, LOOP_N)
    return np.stack([np.interp(x, np.arange(v.shape[1]), a) for a in v])


def fit8(x1, x2, kappa):
    c = x1 @ x1.T
    lam = kappa * np.trace(c) / len(c)
    eye = np.eye(len(c))
    return (x2 @ x1.T + lam * eye) @ np.linalg.inv(c + lam * eye)


def d8(p, qv, q_on):
    best = -2.0
    for s in range(-LAG, LAG + 1):
        q = qv[:, q_on - WIN[0] + s:q_on + WIN[1] + 1 + s]
        best = max(best, float((p * q).sum() / np.sqrt((p * p).sum() * (q * q).sum() + 1e-12)))
    return 1 - best


def dbar8(a12, a21, t1, t2):
    w1 = t1["pvc"][:, t1["pvc_on"] - WIN[0]:t1["pvc_on"] + WIN[1] + 1]
    w2 = t2["pvc"][:, t2["pvc_on"] - WIN[0]:t2["pvc_on"] + WIN[1] + 1]
    return (d8(a12 @ w1, t2["pvc"], t2["pvc_on"]) + d8(a21 @ w2, t1["pvc"], t1["pvc_on"])) / 2


def load(site):
    tmpl = np.load(OUT / f"{site}_templates.npy", allow_pickle=True)
    pairs = pd.read_parquet(OUT / f"{site}_pairs.parquet")
    pr = pairs[pairs.stratum == STRATUM]
    return [(tmpl[i], tmpl[j]) for i, j in zip(pr.i, pr.j)]


def run(pairs, kappa):
    eye = np.eye(8)
    rows = []
    for a, b in pairs:
        la, lb = sr_loop8(a), sr_loop8(b)
        a12, a21 = fit8(la, lb, kappa), fit8(lb, la, kappa)
        m1 = measures(a["pvc"], a["sr"], a["pvc_on"], a["pvc_off"], a["sr_on"], a["sr_off"])
        m2 = measures(b["pvc"], b["sr"], b["pvc_on"], b["pvc_off"], b["sr_on"], b["sr_off"])
        c12 = measures(a12 @ a["pvc"], b["sr"], a["pvc_on"], a["pvc_off"], b["sr_on"], b["sr_off"])
        c21 = measures(a21 @ b["pvc"], a["sr"], b["pvc_on"], b["pvc_off"], a["sr_on"], a["sr_off"])
        rows.append({"d_raw": dbar8(eye, eye, a, b), "d_own": dbar8(a12, a21, a, b),
                     "tz_c_raw": abs(m1["tz_c"] - m2["tz_c"]),
                     "tz_c_cor": (abs(c12["tz_c"] - m2["tz_c"]) + abs(c21["tz_c"] - m1["tz_c"])) / 2,
                     "tz_g_flip_raw": float(m1["tz_g"] != m2["tz_g"]),
                     "tz_g_flip_cor": ((c12["tz_g"] != m2["tz_g"]) + (c21["tz_g"] != m1["tz_g"])) / 2,
                     "r_v2_raw": abs(m1["r_v2"] - m2["r_v2"]),
                     "r_v2_cor": (abs(c12["r_v2"] - m2["r_v2"]) + abs(c21["r_v2"] - m1["r_v2"])) / 2})
    return pd.DataFrame(rows)


def main():
    mgh = load("mgh")
    grid = []
    for k in KAPPAS + [3.0, 10.0]:
        d = [dbar8(fit8(sr_loop8(a), sr_loop8(b), k), fit8(sr_loop8(b), sr_loop8(a), k), a, b) for a, b in mgh]
        grid.append((k, float(np.median(d))))
    kappa = min([g for g in grid if g[0] in KAPPAS], key=lambda g: g[1])[0]
    lines = ["# H4 with the 8 x 8 lead-space transform (sensitivity, descriptive)", "",
             "Generated by `python -m src.h4_leads`; definitions in the module docstring; `docs/decisions.md` item 29.",
             "Primary-stratum pairs.", "", "## κ8 (median d_own, MGH)", "",
             "| κ8 | median d_own |", "|---|---|"]
    lines += [f"| {k:g}{'' if k in KAPPAS else ' (check, not used)'} | {v:.4f} |" for k, v in grid]
    lines += ["", f"**Chosen κ8 = {kappa}.**", ""]
    for site, pairs in (("mgh", mgh), ("euh", load("euh"))):
        d = run(pairs, kappa)
        d.to_parquet(OUT / f"{site}_h4_leads.parquet")
        share_ = (np.median(d.d_raw) - np.median(d.d_own)) / np.median(d.d_raw)
        lines += [f"## HEEDB-{site.upper()} ({len(d)} patients)", "",
                  f"- 8-lead discrepancy: median d_raw {np.median(d.d_raw):.4f}, d_own {np.median(d.d_own):.4f}; "
                  f"own < raw p = {wilcoxon(d.d_own, d.d_raw, alternative='less').pvalue:.1e}; correctable share {share_:.3f}.",
                  "", "| Measure | Raw | 8 x 8 corrected | p |", "|---|---|---|---|",
                  f"| PVC precordial transition, |change| in leads | {med(d.tz_c_raw)} | {med(d.tz_c_cor)} | {wilcoxon(d.tz_c_raw, d.tz_c_cor).pvalue:.1e} |",
                  f"| PVC transition change ≥ 0.5 lead | {share(d.tz_c_raw >= 0.5)} | {share(d.tz_c_cor >= 0.5)} | |",
                  f"| PVC transition change ≥ 1 lead | {share(d.tz_c_raw >= 1)} | {share(d.tz_c_cor >= 1)} | |",
                  f"| PVC graded transition differs | {d.tz_g_flip_raw.mean():.1%} | {d.tz_g_flip_cor.mean():.1%} | "
                  f"{wilcoxon((d.tz_g_flip_raw - d.tz_g_flip_cor)[lambda v: v != 0]).pvalue:.1e} |",
                  f"| PVC r in V2, |change| | {med(d.r_v2_raw)} | {med(d.r_v2_cor)} | {wilcoxon(d.r_v2_raw, d.r_v2_cor).pvalue:.1e} |", ""]
    (DOCS / "wp2_h4_leads.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
