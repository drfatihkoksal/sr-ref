"""Test-retest reliability of the published SR-referenced OT-PVC criteria (post hoc, label-free;
docs/decisions.md item 30).

Pairs: the primary-stratum pairs of `src.stage_a` (two ECGs of one patient, matched PVC morphology
r >= 0.85, <= 365 days) on HEEDB-MGH and HEEDB-EUH. Each ECG is measured on its own PVC and SR
templates (`h4_clinical.measures`): V2 transition ratio (LVOT call >= 0.60; Betensky 2011) and TZ
index (graded, LVOT call < 0; Yoshida 2011). III and aVF come from I and II.

Scope, as published, from the first ECG of the pair: V2TR for PVCs with LBBB morphology (r V1 <
0.5), inferior axis (r > 0.5 in II, III, aVF) and a V3 precordial transition (r V2 < 0.5 <= r V3);
TZ index for LBBB with inferior axis.

Per subset: share of pairs whose call differs between the two ECGs (f, Wilson 95% CI), Cohen's κ of
the two calls, and the accuracy ceiling this implies for a single ECG when the origin is fixed:
at most 1 - f/2 (two ECGs cannot both be right when they disagree), and 1 - e with
e = (1 - sqrt(1 - 2f))/2 if the errors of the two ECGs are independent. Subsets: all pairs; in scope;
stricter match (r >= 0.95); same day (< 24 h) vs 1-365 days.

    python -m src.criteria_reliability   -> docs/wp2_criteria_reliability.md
"""
import numpy as np
import pandas as pd

from src.audit import wilson
from src.config import DOCS, LEADS8
from src.h4 import OUT
from src.h4_clinical import measures, rfrac

I, II, V1, V2, V3 = (LEADS8.index(x) for x in ("I", "II", "V1", "V2", "V3"))


def scope(t):
    P = t["pvc"]
    limb = np.stack([P[II], P[II] - P[I], P[II] - P[I] / 2])          # II, III, aVF
    r_inf = rfrac(limb, t["pvc_on"], t["pvc_off"])
    r = rfrac(P, t["pvc_on"], t["pvc_off"])
    lbbb_inf = bool(r[V1] < 0.5 and (r_inf > 0.5).all())
    return lbbb_inf, lbbb_inf and bool(r[V2] < 0.5 <= r[V3])


def table(site):
    tmpl = np.load(OUT / f"{site}_templates.npy", allow_pickle=True)
    pairs = pd.read_parquet(OUT / f"{site}_pairs.parquet")
    pr = pairs[pairs.stratum.str.startswith("primary")]
    rows = []
    for i, j, days, r in zip(pr.i, pr.j, pr.days, pr.r):
        a, b = tmpl[i], tmpl[j]
        m = [measures(t["pvc"], t["sr"], t["pvc_on"], t["pvc_off"], t["sr_on"], t["sr_off"]) for t in (a, b)]
        lbbb_inf, v3 = scope(a)
        rows.append({"days": days, "r": r, "scope_tzi": lbbb_inf, "scope_v2tr": v3,
                     "v2tr_1": m[0]["v2tr"] >= 0.60, "v2tr_2": m[1]["v2tr"] >= 0.60,
                     "tzi_1": m[0]["tzi_g"] < 0, "tzi_2": m[1]["tzi_g"] < 0})
    return pd.DataFrame(rows)


def kappa(x, y):
    po = np.mean(x == y)
    pe = np.mean(x) * np.mean(y) + (1 - np.mean(x)) * (1 - np.mean(y))
    return (po - pe) / (1 - pe) if pe < 1 else np.nan


def row(name, d, c):
    if not len(d):
        return f"| {name} | 0 | — | — | — | — | — |"
    x, y = d[f"{c}_1"].to_numpy(), d[f"{c}_2"].to_numpy()
    k, n = int((x != y).sum()), len(d)
    f = k / n
    lo, hi = wilson(k, n)
    e = (1 - np.sqrt(max(1 - 2 * f, 0))) / 2
    return (f"| {name} | {n} | {np.mean(x):.0%} | {f:.1%} ({lo:.1%} to {hi:.1%}) | {kappa(x, y):.2f} | "
            f"≤ {1 - f / 2:.1%} | {1 - e:.1%} |")


def main():
    lines = ["# Test-retest reliability of SR-referenced OT-PVC criteria (post hoc, label-free)", "",
             "Generated by `python -m src.criteria_reliability`; definitions in the module docstring;",
             "`docs/decisions.md` item 30. LVOT share: share of first ECGs with an LVOT call. Ceiling: accuracy a",
             "single ECG can reach if the origin is fixed (bound; and under independent errors).", ""]
    for site in ("mgh", "euh"):
        d = table(site)
        d.to_parquet(OUT / f"{site}_criteria_reliability.parquet")
        hdr = ["| Subset | Pairs | LVOT calls | Call differs (95% CI) | κ | Ceiling (bound) | Ceiling (independent) |",
               "|---|---|---|---|---|---|---|"]
        for c, name, sc in (("v2tr", "V2 transition ratio (≥ 0.60)", "scope_v2tr"),
                            ("tzi", "TZ index (< 0)", "scope_tzi")):
            lines += [f"## HEEDB-{site.upper()}: {name}", ""] + hdr + [
                row("All pairs", d, c),
                row("In published scope", d[d[sc]], c),
                row("In scope, match r ≥ 0.95", d[d[sc] & (d.r >= 0.95)], c),
                row("In scope, same day", d[d[sc] & (d.days < 1)], c),
                row("In scope, 1-365 days", d[d[sc] & (d.days >= 1)], c), ""]
    (DOCS / "wp2_criteria_reliability.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))





# ---- multifocality checks (docs/decisions.md item 31) -------------------------------------------------
# `python -m src.criteria_reliability multifocal` -> docs/wp2_criteria_multifocal.md. V2TR pairs in scope.
# 1. Patients with any record excluded for "more than one PVC cluster" (multiform PVCs within one ECG)
#    vs none. 2. Patients with >= 3 eligible OT-like ECGs: all PVC templates mutually matched (r >= 0.85)
#    vs at least one pair not matched (another morphology). 3. Calls after the 8 x 8 own-SR transform
#    maps one ECG's PVC into the other ECG's lead space (mean of both directions). 4. Size of the change
#    (|log V2TR ratio|) in pairs whose call differs vs agrees, and the share of differing calls with both
#    values within 0.40-0.90.


def multifocal():
    from itertools import combinations

    from src.h4_leads import fit8, sr_loop8
    from src.stage_a import match_r
    lines = ["# Multifocality checks of the V2TR test-retest result (post hoc, label-free)", "",
             "Generated by `python -m src.criteria_reliability multifocal`; definitions at the end of the module;",
             "`docs/decisions.md` item 31. V2TR (≥ 0.60) pairs in the published scope, primary stratum.", ""]
    for site in ("mgh", "euh"):
        rec = pd.read_parquet(OUT / f"{site}_records.parquet")
        tmpl = np.load(OUT / f"{site}_templates.npy", allow_pickle=True)
        pairs = pd.read_parquet(OUT / f"{site}_pairs.parquet")
        pr = pairs[pairs.stratum.str.startswith("primary")].reset_index(drop=True)
        rel = pd.read_parquet(OUT / f"{site}_criteria_reliability.parquet")
        pr = pd.concat([pr, rel], axis=1)
        pr = pr[pr.scope_v2tr].copy()
        pr["patient"] = rec.patient.loc[pr.i].to_numpy()
        multiform = set(rec.patient[rec.reason == "more than one PVC cluster"])
        pr["multiform"] = pr.patient.isin(multiform)
        ot = rec[rec.reason == "OT-like"]
        consistent = {}
        for pid, g in ot.groupby("patient"):
            if len(g) >= 3:
                rs = [match_r(tmpl[a]["pvc"], tmpl[b]["pvc"], tmpl[a]["pvc_on"], tmpl[b]["pvc_on"])
                      for a, b in combinations(g.index, 2)]
                consistent[pid] = min(rs) >= 0.85
        pr["consistent"] = pr.patient.map(consistent)
        cor_flip, logratio = [], []
        for i, j in zip(pr.i, pr.j):
            a, b = tmpl[i], tmpl[j]
            a12, a21 = fit8(sr_loop8(a), sr_loop8(b), 1.0), fit8(sr_loop8(b), sr_loop8(a), 1.0)
            v1 = measures(a["pvc"], a["sr"], a["pvc_on"], a["pvc_off"], a["sr_on"], a["sr_off"])["v2tr"]
            v2 = measures(b["pvc"], b["sr"], b["pvc_on"], b["pvc_off"], b["sr_on"], b["sr_off"])["v2tr"]
            c12 = measures(a12 @ a["pvc"], b["sr"], a["pvc_on"], a["pvc_off"], b["sr_on"], b["sr_off"])["v2tr"]
            c21 = measures(a21 @ b["pvc"], a["sr"], b["pvc_on"], b["pvc_off"], a["sr_on"], a["sr_off"])["v2tr"]
            cor_flip.append((int((c12 >= 0.6) != (v2 >= 0.6)) + int((c21 >= 0.6) != (v1 >= 0.6))) / 2)   # int: NumPy bools add as OR
            logratio.append(abs(np.log(max(v1, 1e-3) / max(v2, 1e-3))))
        pr["cor_flip"], pr["logratio"] = cor_flip, logratio
        pr["flip"] = pr.v2tr_1 != pr.v2tr_2
        f = lambda d: f"{d.flip.mean():.1%} (n {len(d)})" if len(d) else "—"
        flips = pr[pr.flip]
        lines += [f"## HEEDB-{site.upper()} ({len(pr)} pairs in scope)", "",
                  "| Check | Call differs |", "|---|---|",
                  f"| All pairs in scope | {f(pr)} |",
                  f"| Patients with multiform PVCs in any ECG | {f(pr[pr.multiform])} |",
                  f"| Patients without | {f(pr[~pr.multiform])} |",
                  f"| ≥ 3 ECGs, all PVCs mutually matched | {f(pr[pr.consistent == True])} |",  # noqa: E712
                  f"| ≥ 3 ECGs, at least one PVC not matched | {f(pr[pr.consistent == False])} |",  # noqa: E712
                  f"| Raw calls vs after 8 x 8 placement transform | {pr.flip.mean():.1%} -> {pr.cor_flip.mean():.1%} |", "",
                  f"- Size of the change, |log V2TR ratio|: median {flips.logratio.median():.2f} when the call differs, "
                  f"{pr[~pr.flip].logratio.median():.2f} when it agrees.",
                  f"- Differing calls with both values within 0.40–0.90: "
                  f"{np.mean([(0.4 <= min(a, b)) and (max(a, b) <= 0.9) for a, b in zip(*[[measures(tmpl[k]['pvc'], tmpl[k]['sr'], tmpl[k]['pvc_on'], tmpl[k]['pvc_off'], tmpl[k]['sr_on'], tmpl[k]['sr_off'])['v2tr'] for k in flips[c]] for c in ('i', 'j')])]):.1%}.", ""]
    (DOCS / "wp2_criteria_multifocal.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    import sys
    multifocal() if sys.argv[1:] == ["multifocal"] else main()
