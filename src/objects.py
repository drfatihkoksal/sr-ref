"""Stage A objects for Stage B (analysis plan 5.6), fitted on HEEDB-MGH only.

Patients: HEEDB-MGH patients with an eligible OT-like recording among those processed by
`src.stage_a cohort` (patients with at least two 500-Hz PVC records); per patient the first such
recording in time.
- Canonical SR template: sample-wise median of the SR loops (3 x 100, µV; `h4.sr_loop`).
- Raw-PVC basis (k = 6): PCA of the PVC windows (3 x 96 -> 288, `h4.window`), mean-centred, not
  scaled.
- Normalised-PVC basis (k = 6): the same windows after N: A_i maps the patient's SR loop to the
  canonical template (`h4.fit_a`, frozen κ) and is applied to the PVC window.
- SR basis (k = 3): PCA of the SR loops (300).
κ and the placement noise model come from `src.h4`. Everything is saved to ARTIFACTS/wp2/objects
with SHA-256 content hashes (stable across reruns); the formal freeze is at gate K2 (plan 8).

    python -m src.objects   -> docs/wp2_objects.md
"""
import hashlib
import json

import numpy as np
import pandas as pd

from src.config import DOCS
from src.h4 import OBJ, OUT, fit_a, pvc_vcg, sr_loop, window

K = {"raw_pvc": 6, "norm_pvc": 6, "sr": 3}


def pca(x, k):
    mean = x.mean(0)
    u, s, vt = np.linalg.svd(x - mean, full_matrices=False)
    var = s ** 2 / (len(x) - 1)
    return {"mean": mean, "components": vt[:k], "explained": var[:k] / var.sum()}


def sha(path):
    """Content hash: for .npz the arrays (names, dtypes, shapes, bytes), since the zip container stores
    timestamps; otherwise the file bytes."""
    if path.suffix != ".npz":
        return hashlib.sha256(path.read_bytes()).hexdigest()
    h = hashlib.sha256()
    with np.load(path) as z:
        for k in sorted(z.files):
            a = np.ascontiguousarray(z[k])
            h.update(f"{k}|{a.dtype}|{a.shape}|".encode())
            h.update(a.tobytes())
    return h.hexdigest()


def main():
    rec = pd.read_parquet(OUT / "mgh_records.parquet")
    tmpl = np.load(OUT / "mgh_templates.npy", allow_pickle=True)
    kappa = json.loads((OBJ / "kappa.json").read_text())["kappa"]
    first = rec[rec.reason == "OT-like"].sort_values("time").groupby("patient").head(1).index
    loops = np.stack([sr_loop(tmpl[i]) for i in first])
    pvc = np.stack([window(*pvc_vcg(tmpl[i])) for i in first])
    template = np.median(loops, axis=0)
    norm = np.stack([fit_a(l, template, kappa) @ p for l, p in zip(loops, pvc)])
    bases = {"raw_pvc": pca(pvc.reshape(len(pvc), -1), K["raw_pvc"]),
             "norm_pvc": pca(norm.reshape(len(norm), -1), K["norm_pvc"]),
             "sr": pca(loops.reshape(len(loops), -1), K["sr"])}
    np.save(OBJ / "sr_template.npy", template)
    rms = np.sqrt((loops ** 2).mean(axis=(1, 2)))
    (OBJ / "sr_loop_rms.json").write_text(json.dumps({"median_uv": float(np.median(rms)), "n": len(rms)}))
    for name, b in bases.items():
        np.savez(OBJ / f"basis_{name}.npz", **b)
    files = ["kappa.json", "noise_A.npy", "sr_template.npy", "sr_loop_rms.json"]
    files += [f"basis_{n}.npz" for n in bases]
    files += ["ningbo_scale.json"] if (OBJ / "ningbo_scale.json").exists() else []   # from src.ningbo
    hashes = {f: sha(OBJ / f) for f in files}
    (OBJ / "hashes.json").write_text(json.dumps(hashes, indent=1))
    noise = np.load(OBJ / "noise_A.npy")
    dev = np.linalg.norm(noise - np.eye(3), axis=(1, 2))
    amp = lambda x: np.sqrt((x ** 2).sum(axis=(1, 2)) / x[0].size)
    lines = ["# WP2: Stage A objects (HEEDB-MGH)", "",
             "Generated by `python -m src.objects`; definitions in the module docstring and plan 5.6. Formal freeze",
             "at gate K2. Objects and hashes in `ARTIFACTS/wp2/objects/` (`hashes.json`).", "",
             f"- Patients (first eligible OT-like recording each): {len(first)}.",
             f"- κ = {kappa}; placement noise model: {len(noise)} matrices (both directions of the primary H4 pairs); "
             f"||A − I||_F median {np.median(dev):.3f} (IQR {np.percentile(dev, 25):.3f} to {np.percentile(dev, 75):.3f}).",
             f"- Canonical SR template: 3 × {template.shape[1]} points, RMS {np.sqrt((template ** 2).mean()):.0f} µV; "
             f"SR loop RMS across patients median {np.median(amp(loops)):.0f} µV.",
             f"- PVC window RMS median {np.median(amp(pvc)):.0f} µV; after N {np.median(amp(norm)):.0f} µV.", "",
             "| Basis | k | Explained variance per component | Cumulative |", "|---|---|---|---|"]
    for name, b in bases.items():
        e = b["explained"]
        lines.append(f"| {name} | {len(e)} | {', '.join(f'{v:.3f}' for v in e)} | {e.sum():.3f} |")
    lines += ["", "SHA-256 (first 16 characters): " + "; ".join(f"`{f}` {h[:16]}" for f, h in hashes.items()) + "."]
    (DOCS / "wp2_objects.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
