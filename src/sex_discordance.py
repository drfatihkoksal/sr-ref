"""Discordance of the V2TR and TZ index calls by sex (post hoc, exploratory, label-free; outside the
registration https://osf.io/wyx28; docs/decisions.md item 40).

Sex is as recorded in the source, at the first ECG of the pair: HEEDB metadata (SexDSC at MGH, Sex at Emory) and
the `gender` field of the MIMIC-IV patients table. Pairs: primary stratum, both ECGs in the published scope of the
criterion. Per source and sex: discordance (Wilson 95% CI), Cohen's κ of the two calls and the accuracy ceiling.
Women minus men: difference with a 95% CI from 2000 resamples within sex. Pooled difference: Mantel-Haenszel weights
across source and interval class (same day, 1-365 days), 2000 resamples within strata.

    python -m src.sex_discordance   -> docs/wp3_sex_discordance.md
"""
import numpy as np
import pandas as pd

from src.audit import wilson
from src.config import ARTIFACTS, DOCS, N_BOOT, SEED
from src.criteria_reliability import kappa
from src.h4 import OUT, demographics as heedb_demographics
from src.mimic_rep import demographics as mimic_demographics

OUT3 = ARTIFACTS / "wp3"
SITES = {"mgh": (OUT, "HEEDB-MGH"), "euh": (OUT, "HEEDB-Emory"), "mimic": (OUT3, "MIMIC-IV-ECG")}
PRIMARY = "primary (<= 365 days)"
CRITERIA = {"v2tr": "V2TR (≥ 0.60)", "tzi": "TZ index (< 0)"}


def frame(key, root):
    rec = pd.read_parquet(root / f"{key}_records.parquet")
    pairs = pd.read_parquet(root / f"{key}_pairs.parquet")
    pr = pairs[pairs.stratum == PRIMARY].reset_index(drop=True)
    sex = (mimic_demographics(rec) if key == "mimic" else heedb_demographics(key, rec.file))[0]
    stem = rec.file.str.rsplit("/", n=1).str[-1].to_numpy()
    d = pd.read_parquet(root / ("mimic_criteria.parquet" if key == "mimic" else f"{key}_criteria_controls.parquet"))
    if len(d) != len(pr):
        raise SystemExit(f"{key}: criteria and pairs differ in length")
    label = lambda v: "women" if str(v).upper().startswith("F") else "men" if str(v).upper().startswith("M") else "unknown"
    d["sex"] = [label(v) for v in sex.reindex(stem[pr.i]).to_numpy()]
    d["source"] = key
    d["same_day"] = d.days < 1
    return d


def group(g, c):
    x, y = g[f"{c}_1"].to_numpy(bool), g[f"{c}_2"].to_numpy(bool)
    k, n = int((x != y).sum()), len(g)
    lo, hi = wilson(k, n)
    return {"k": k, "n": n, "f": k / n, "lo": max(float(lo), 0.0), "hi": float(hi), "kappa": float(kappa(x, y)), "ceiling": 1 - k / n / 2}


def difference(f, m):
    rng = np.random.default_rng(SEED)
    boots = [f[rng.integers(0, len(f), len(f))].mean() - m[rng.integers(0, len(m), len(m))].mean() for _ in range(N_BOOT)]
    return {"m": float(f.mean() - m.mean()), "lo": float(np.percentile(boots, 2.5)), "hi": float(np.percentile(boots, 97.5))}


def pooled(d, c):
    """Mantel-Haenszel difference, women minus men, across source and interval class."""
    cells = []
    for _, g in d.groupby(["source", "same_day"]):
        f, m = g[g.sex == "women"][f"{c}_raw"].to_numpy(float), g[g.sex == "men"][f"{c}_raw"].to_numpy(float)
        if len(f) and len(m):
            cells.append((f, m, len(f) * len(m) / (len(f) + len(m))))
    total = sum(w for *_, w in cells)
    rng = np.random.default_rng(SEED)
    boots = [sum(w * (f[rng.integers(0, len(f), len(f))].mean() - m[rng.integers(0, len(m), len(m))].mean()) for f, m, w in cells) / total for _ in range(N_BOOT)]
    return {"m": float(sum(w * (f.mean() - m.mean()) for f, m, w in cells) / total), "lo": float(np.percentile(boots, 2.5)), "hi": float(np.percentile(boots, 97.5)), "strata": len(cells)}


def compute():
    frames = {k: frame(k, root) for k, (root, _) in SITES.items()}
    numbers, lines = {}, ["# V2TR and TZ index discordance by sex (exploratory, post hoc, label-free)", "",
                          "Generated by `python -m src.sex_discordance`; definitions in the module docstring. Outside the registration",
                          "https://osf.io/wyx28. Primary stratum, both ECGs in the published scope of the criterion.", ""]
    for c, label in CRITERIA.items():
        numbers[c] = {}
        lines += [f"## {label}", "", "| Source | Women: call differs (Wilson 95% CI) | κ | Ceiling | Men: call differs (Wilson 95% CI) | κ | Ceiling | Women minus men, points (95% CI) | Sex unknown |",
                  "|---|---|---|---|---|---|---|---|---|"]
        scoped = []
        for key, (_, name) in SITES.items():
            d = frames[key]
            g = d[d[f"{c}_both"]]
            scoped.append(g)
            f, m = g[g.sex == "women"], g[g.sex == "men"]
            a, b = group(f, c), group(m, c)
            dif = difference(f[f"{c}_raw"].to_numpy(float), m[f"{c}_raw"].to_numpy(float))
            numbers[c][key] = {"women": a, "men": b, "difference": dif, "unknown": int((g.sex == "unknown").sum())}
            lines.append(f"| {name} | {a['k']}/{a['n']} = {a['f']:.1%} ({a['lo']:.1%} to {a['hi']:.1%}) | {a['kappa']:.2f} | ≤ {a['ceiling']:.1%} | "
                         f"{b['k']}/{b['n']} = {b['f']:.1%} ({b['lo']:.1%} to {b['hi']:.1%}) | {b['kappa']:.2f} | ≤ {b['ceiling']:.1%} | "
                         f"{dif['m'] * 100:+.1f} ({dif['lo'] * 100:+.1f} to {dif['hi'] * 100:+.1f}) | {numbers[c][key]['unknown']} |")
        pool = pooled(pd.concat(scoped), c)
        numbers[c]["pooled"] = pool
        lines += ["", f"Pooled difference, women minus men, adjusted for source and interval class: {pool['m'] * 100:+.1f} points (95% CI "
                      f"{pool['lo'] * 100:+.1f} to {pool['hi'] * 100:+.1f}; {pool['strata']} strata).", ""]
    return numbers, lines


def main():
    _, lines = compute()
    (DOCS / "wp3_sex_discordance.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
