"""Sensitivity of the V2TR discordance to the published sinus measurement rule (exploratory, post hoc,
label-free, outside the registration https://osf.io/wyx28; docs/decisions.md item 39).

The main analysis measures the sinus R and S on the median SR template. Betensky 2011 took the largest
R and the largest S over 10 s of sinus rhythm, against respiratory variation. Here every SR beat of the
recording is measured in V2 within its own QRS window, from the mean of the 20 ms before its QRS onset,
and r_SR = max R / (max R + max S). The PVC template is unchanged, so only the SR denominator changes.

Pairs: primary stratum, both ECGs in the published V2TR scope. Records are processed again with the
locked detector; the stored SR templates must be reproduced. Differences of discordance with a 95% CI
from 2000 patient resamples.

    python -m src.betensky_rule   -> docs/wp3_betensky_rule.md
"""
import os
import warnings
from concurrent.futures import ProcessPoolExecutor

import numpy as np
import pandas as pd

from src.audit import wilson
from src.beats import MS
from src.config import ARTIFACTS, DOCS, LEADS12, QRS_OFFSET_MS
from src.criteria_controls import diff_ci
from src.criteria_reliability import scope
from src.h4 import OUT
from src.h4_clinical import V2, rfrac
from src.records import BASE, extremum, load, process
from src.signal import IDX8

OUT3 = ARTIFACTS / "wp3"
SOURCES = {"HEEDB-MGH": (OUT, "mgh", "heedb"), "HEEDB-Emory": (OUT, "euh", "heedb"), "MIMIC-IV-ECG": (OUT3, "mimic", "mimic")}
V2_12 = LEADS12.index("V2")


def _measure(task):
    f, dataset = task
    try:
        x, fs = load(f)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            r = process(x, fs, dataset)
    except Exception:
        return None
    if r.get("sr") is None or "x12" not in r:
        return None
    y = r["x12"][V2_12]
    R, S = [], []
    for on, q in zip(r["beats"].loc[r["beats"].cls == "SR", "on"].astype(int), r["beats"].loc[r["beats"].cls == "SR", "qrs_ms"]):
        off = on + int(round((q - QRS_OFFSET_MS) * MS))
        if on - BASE < 0 or off >= len(y):
            continue
        z = y - y[on - BASE:on].mean()
        R.append(extremum(z, on, off, 1))
        S.append(extremum(z, on, off, -1))
    if not R:
        return None
    return max(R), max(S), len(R), r["sr"]["T"][IDX8].astype(np.float32)


def source_rows(root, key, dataset):
    rec = pd.read_parquet(root / f"{key}_records.parquet")
    tmpl = np.load(root / f"{key}_templates.npy", allow_pickle=True)
    pairs = pd.read_parquet(root / f"{key}_pairs.parquet")
    pr = pairs[pairs.stratum.str.startswith("primary")].reset_index(drop=True)
    pr = pr[[scope(tmpl[i])[1] and scope(tmpl[j])[1] for i, j in zip(pr.i, pr.j)]].reset_index(drop=True)
    need = sorted(set(pr.i) | set(pr.j))
    os.environ.setdefault("OMP_NUM_THREADS", "1")
    with ProcessPoolExecutor(max_workers=max(os.cpu_count() - 4, 1)) as ex:
        res = dict(zip(need, ex.map(_measure, [(rec.file[k], dataset) for k in need], chunksize=20)))
    same = np.mean([res[k] is not None and res[k][3].shape == tmpl[k]["sr"].shape and np.allclose(res[k][3], tmpl[k]["sr"], atol=0.01) for k in need])
    out, lost = [], 0
    for i, j, days in zip(pr.i, pr.j, pr.days):
        if res[i] is None or res[j] is None:
            lost += 1
            continue
        row = {"days": days, "beats": min(res[i][2], res[j][2])}
        calls = []
        for t, m in ((tmpl[i], res[i]), (tmpl[j], res[j])):
            rp = rfrac(t["pvc"], t["pvc_on"], t["pvc_off"])[V2]
            st = rfrac(t["sr"], t["sr_on"], t["sr_off"])[V2]
            sb = m[0] / (m[0] + m[1]) if m[0] + m[1] > 0 else 0.0
            calls.append((rp / max(st, 0.01) >= 0.60, rp / max(sb, 0.01) >= 0.60, abs(sb - st)))
        row["template"] = float(calls[0][0] != calls[1][0])
        row["rule"] = float(calls[0][1] != calls[1][1])
        row["ecg_changed"] = (int(calls[0][0] != calls[0][1]) + int(calls[1][0] != calls[1][1])) / 2
        row["sr_change"] = (calls[0][2] + calls[1][2]) / 2
        out.append(row)
    return pd.DataFrame(out), same, lost


def main():
    lines = ["# Sensitivity of the V2TR discordance to the published sinus measurement rule (exploratory, post hoc, label-free)", "",
             "Generated by `python -m src.betensky_rule`; definitions in the module docstring. Outside the registration",
             "https://osf.io/wyx28. Primary stratum, both ECGs in the V2TR scope. Only the SR denominator changes.", "",
             "| Source | Pairs | SR templates reproduced | Median template rule | Largest R and S over 10 s (Wilson 95% CI) | Ceiling, published rule | Difference, points (95% CI) | ECGs whose call changes | Median change of SR r |",
             "|---|---|---|---|---|---|---|---|---|"]
    for name, (root, key, dataset) in SOURCES.items():
        d, same, lost = source_rows(root, key, dataset)
        k, n = int(d.rule.sum()), len(d)
        lo, hi = wilson(k, n)
        f = k / n
        lines.append(f"| {name} | {n}{f' ({lost} lost)' if lost else ''} | {same:.1%} | {d.template.mean():.1%} | {f:.1%} ({lo:.1%} to {hi:.1%}) | ≤ {1 - f / 2:.1%} | "
                     f"{diff_ci(d.rule, d.template)} | {d.ecg_changed.mean():.1%} | {d.sr_change.median():.3f} |")
    (DOCS / "wp3_betensky_rule.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
