"""Blinded human measurement of V2 R and S in MIMIC-IV-ECG pairs (exploratory, outside the registration;
protocol prereg/V2_READER_VALIDATION.md; docs/decisions.md item 37).

    python -m src.v2_readers sample   -> ARTIFACTS/wp3/readers/key.csv, items.npy, sample.json;
                                         docs/wp3_readers_sample.md (counts only)
    python -m src.v2_readers pages    -> ARTIFACTS/wp3/readers/reader1.html, reader2.html
    python -m src.v2_readers score    -> docs/wp3_readers_result.md (reads reader1_form.csv, reader2_form.csv)

`--test DIR` builds a synthetic sample in DIR and sends every output there; real data are not read.
Row-level files stay under ARTIFACTS. Each item shows lead V2 of the PVC and SR templates only.
"""
import argparse
import base64
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from src.audit import wilson
from src.config import ARTIFACTS, DOCS, N_BOOT, SEED
from src.criteria_reliability import kappa
from src.h4_clinical import V2, rfrac

OUT3 = ARTIFACTS / "wp3"
PAGE = Path(__file__).with_name("v2_readers.html")
READERS = {"reader1": "Fatih Köksal", "reader2": "Fatih Levent"}
PER_STRATUM = 25                # pairs per automated stratum (50 ECGs per stratum, 100 ECGs in total)
FS = 500
T0, T1 = 30, 150                # samples shown before and after the QRS onset: -60 to +300 ms
LVOT, QS = 0.60, 0.05
WHO = ("joint", "reader1", "reader2")


def write_sample(out, rows, items, pop):
    rows = pd.DataFrame(rows)
    order = np.random.default_rng(SEED).permutation(len(rows))
    rows = rows.iloc[order].reset_index(drop=True)
    rows.insert(0, "code", [f"E{i + 1:03d}" for i in range(len(rows))])
    rows.to_csv(out / "key.csv", index=False)
    np.save(out / "items.npy", np.array([{"code": c, **items[k]} for c, k in zip(rows.code, order)], dtype=object), allow_pickle=True)
    (out / "sample.json").write_text(json.dumps(pop))


def sample(out, docs):
    if (out / "key.csv").exists():
        raise SystemExit("key.csv exists: the sample is fixed; delete it only with the author's approval")
    out.mkdir(parents=True, exist_ok=True)
    tmpl = np.load(OUT3 / "mimic_templates.npy", allow_pickle=True)
    pairs = pd.read_parquet(OUT3 / "mimic_pairs.parquet")
    pr = pairs[pairs.stratum.str.startswith("primary")].reset_index(drop=True)
    crit = pd.read_parquet(OUT3 / "mimic_criteria.parquet")
    both = crit[crit.v2tr_both]
    groups = {"discordant": both.index[both.v2tr_raw == 1], "concordant": both.index[both.v2tr_raw == 0]}
    rng = np.random.default_rng(SEED)
    rows, items = [], []
    for stratum, idx in groups.items():
        for k in sorted(rng.choice(idx, PER_STRATUM, replace=False)):
            for ecg, rec in ((1, pr.i[k]), (2, pr.j[k])):
                t = tmpl[rec]
                rp, rs = rfrac(t["pvc"], t["pvc_on"], t["pvc_off"])[V2], rfrac(t["sr"], t["sr_on"], t["sr_off"])[V2]
                v = rp / max(rs, 0.01)
                rows.append({"pair": int(k), "ecg": ecg, "stratum": stratum, "auto_r_pvc": float(rp), "auto_r_sr": float(rs),
                             "auto_v2tr": float(v), "auto_call": bool(v >= LVOT)})
                items.append({"pvc": t["pvc"][V2, t["pvc_on"] - T0:t["pvc_on"] + T1 + 1].astype(np.float32),
                              "sr": t["sr"][V2, t["sr_on"] - T0:t["sr_on"] + T1 + 1].astype(np.float32)})
    pop = {"discordant": int(len(groups["discordant"])), "concordant": int(len(groups["concordant"]))}
    write_sample(out, rows, items, pop)
    lines = ["# MIMIC-IV-ECG reader validation: sample (counts only)", "",
             "Generated by `python -m src.v2_readers sample`; protocol `prereg/V2_READER_VALIDATION.md`.", "",
             f"- Population: {pop['discordant'] + pop['concordant']} primary-stratum pairs with both ECGs in the V2TR scope: "
             f"{pop['discordant']} automated-discordant and {pop['concordant']} automated-concordant.",
             f"- Sample: {PER_STRATUM} pairs per stratum, {2 * PER_STRATUM} pairs and {4 * PER_STRATUM} ECGs (seed {SEED})."]
    (docs / "wp3_readers_sample.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def synthetic(out):
    """Six synthetic pairs, for testing the page and the score step; no real data."""
    out.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(0)
    t = np.arange(T0 + T1 + 1)
    wave = lambda r, s: r * np.exp(-(t - T0 - 15) ** 2 / 50) - s * np.exp(-(t - T0 - 35) ** 2 / 160) + rng.normal(0, 4, len(t))
    rows, items = [], []
    for pair in range(6):
        for ecg in (1, 2):
            rv, sv = (0.0 if (pair < 3 and ecg == 1) else float(rng.uniform(150, 500))), float(rng.uniform(800, 1800))
            rs, ss = float(rng.uniform(150, 400)), float(rng.uniform(600, 1200))
            p = rv / (rv + sv)
            q = rs / (rs + ss)
            rows.append({"pair": pair, "ecg": ecg, "stratum": "discordant" if pair < 3 else "concordant", "auto_r_pvc": p, "auto_r_sr": q,
                         "auto_v2tr": p / max(q, 0.01), "auto_call": p / max(q, 0.01) >= LVOT})
            items.append({"pvc": wave(rv, sv).astype(np.float32), "sr": wave(rs, ss).astype(np.float32)})
    write_sample(out, rows, items, {"discordant": 12, "concordant": 20})


def b64(a):
    return base64.b64encode(np.ascontiguousarray(a, dtype="<i2").tobytes()).decode()


def pages(out):
    items = list(np.load(out / "items.npy", allow_pickle=True))
    payload = []
    for c in items:
        top = float(np.abs(np.r_[c["pvc"], c["sr"]]).max()) or 1.0
        payload.append({"code": c["code"], "pvc": b64(np.round(c["pvc"] / top * 32000)), "sr": b64(np.round(c["sr"] / top * 32000)), "scale": top / 32000})
    html = PAGE.read_text(encoding="utf-8")
    sample_id = hashlib.sha256((out / "key.csv").read_bytes()).hexdigest()[:12]
    for i, (reader, name) in enumerate(READERS.items(), start=1):
        order = np.random.default_rng(SEED + i).permutation(len(payload))
        data = {"reader": reader, "name": name, "sample_id": sample_id, "fs": FS, "t0": T0, "cases": [payload[j] for j in order]}
        (out / f"{reader}.html").write_text(html.replace("/*__DATA__*/null", json.dumps(data)), encoding="utf-8")
    print("pages: " + ", ".join(str(out / f"{r}.html") for r in READERS))


def derive(e, who):
    rp = (e[f"{who}_pvc_R"] / (e[f"{who}_pvc_R"] + e[f"{who}_pvc_S"])).where(e[f"{who}_pvc_R"] + e[f"{who}_pvc_S"] > 0, 0.0)
    rs = (e[f"{who}_sr_R"] / (e[f"{who}_sr_R"] + e[f"{who}_sr_S"])).where(e[f"{who}_sr_R"] + e[f"{who}_sr_S"] > 0, 0.0)
    e[f"{who}_rp"] = rp.where(e[f"{who}_ok"])
    e[f"{who}_call"] = (rp / rs.clip(lower=0.01) >= LVOT).where(e[f"{who}_ok"])
    e[f"{who}_qs"] = (rp < QS).where(e[f"{who}_ok"])


def ecg_table(out):
    e = pd.read_csv(out / "key.csv").set_index("code")
    fields = ("pvc_R", "pvc_S", "sr_R", "sr_S")
    for r in READERS:
        f = pd.read_csv(out / f"{r}_form.csv", dtype=str, keep_default_na=False).set_index("code").reindex(e.index)
        states = f[["pvc_state", "sr_state"]]
        if (~states.isin(["ok", "unmeasurable"])).any(axis=None):
            raise SystemExit(f"{r}: {int((~states.isin(['ok', 'unmeasurable'])).any(axis=1).sum())} ECGs incomplete")
        e[f"{r}_ok"] = (states == "ok").all(axis=1)
        for c in fields:
            e[f"{r}_{c}"] = pd.to_numeric(f[c], errors="coerce").where(e[f"{r}_ok"])
    e["joint_ok"] = e.reader1_ok & e.reader2_ok
    for c in fields:
        e[f"joint_{c}"] = ((e[f"reader1_{c}"] + e[f"reader2_{c}"]) / 2).where(e.joint_ok)
    for w in WHO:
        derive(e, w)
    return e


def pair_table(e, who):
    """One row per pair evaluable for `who`: stratum and whether the call differs."""
    g = e[e[f"{who}_ok"]].sort_values(["pair", "ecg"]).groupby("pair")
    out = g.agg(stratum=("stratum", "first"), n=("ecg", "size"), differ=(f"{who}_call", lambda v: bool(v.iloc[0] != v.iloc[-1])))
    return out[out.n == 2]


def rate(x):
    n = len(x)
    if not n:
        return "—"
    k = int(np.sum(x))
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {k / n:.1%} ({max(lo, 0):.1%} to {hi:.1%})"


def weighted(p, pop):
    """E2: discordance in the population by stratum weights, with a within-stratum bootstrap."""
    d, c = p[p.stratum == "discordant"].differ.to_numpy(float), p[p.stratum == "concordant"].differ.to_numpy(float)
    nd, nc = pop["discordant"], pop["concordant"]
    if not (len(d) and len(c)):
        return np.nan, np.nan, np.nan
    rng = np.random.default_rng(SEED)
    boots = [(nd * d[rng.integers(0, len(d), len(d))].mean() + nc * c[rng.integers(0, len(c), len(c))].mean()) / (nd + nc) for _ in range(N_BOOT)]
    return (nd * d.mean() + nc * c.mean()) / (nd + nc), np.percentile(boots, 2.5), np.percentile(boots, 97.5)


def agree(a, b):
    ok = a.notna() & b.notna()
    return a[ok].to_numpy(bool), b[ok].to_numpy(bool)


def versus(e, x_rp, x_call, x_qs, y_rp, y_call, y_qs):
    """Agreement of two raters, per ECG: κ of the call, κ of QS-like, differences of r of the PVC."""
    a, b = agree(e[x_call], e[y_call])
    qa, qb = agree(e[x_qs], e[y_qs])
    ok = e[x_rp].notna() & e[y_rp].notna()
    diff = (e[x_rp] - e[y_rp])[ok]
    rho = spearmanr(e[x_rp][ok], e[y_rp][ok]).statistic if ok.sum() > 2 else np.nan
    return (f"{len(a)} | {kappa(a, b):.2f} | {kappa(qa, qb):.2f} | {diff.mean():+.3f} | "
            f"{diff.mean() - 1.96 * diff.std(ddof=1):+.3f} to {diff.mean() + 1.96 * diff.std(ddof=1):+.3f} | {rho:.2f}")


def score(out, docs):
    e = ecg_table(out)
    pop = json.loads((out / "sample.json").read_text())
    e["auto_qs"] = e.auto_r_pvc < QS
    tables = {w: pair_table(e, w) for w in WHO}
    lines = ["# MIMIC-IV-ECG reader validation: result (exploratory, outside the registration)", "",
             "Generated by `python -m src.v2_readers score`; protocol `prereg/V2_READER_VALIDATION.md`. Readers: " + ", ".join(READERS.values()) + ".", "",
             f"Evaluable ECGs of {len(e)}: " + "; ".join(f"{w} {int(e[f'{w}_ok'].sum())}" for w in WHO) + ".",
             f"Evaluable pairs of {e.pair.nunique()}: " + "; ".join(f"{w} {len(tables[w])}" for w in WHO) + ".", "",
             "## E1. Share of pairs whose call differs on human measurement", "",
             "| Automated stratum | Joint reading | Reader 1 | Reader 2 |", "|---|---|---|---|"]
    for s in ("discordant", "concordant"):
        lines.append(f"| {s} | " + " | ".join(rate(tables[w][tables[w].stratum == s].differ) for w in WHO) + " |")
    lines += ["", "## E2. Human discordance in the population, by stratum weights", "",
              f"Population: {pop['discordant']} discordant and {pop['concordant']} concordant pairs; automated discordance "
              f"{pop['discordant'] / (pop['discordant'] + pop['concordant']):.1%}.", "", "| Reading | Estimate | 95% CI |", "|---|---|---|"]
    est = {}
    for w in WHO:
        est[w] = weighted(tables[w], pop)
        lines.append(f"| {w} | {est[w][0]:.1%} | {est[w][1]:.1%} to {est[w][2]:.1%} |")
    m, lo, hi = est["joint"]
    reading = ("human measurement supports the automated finding at the 0.18 threshold" if lo > 0.18 else
               "human measurement supports the automated finding at the 0.10 threshold only" if lo > 0.10 else
               "human measurement does not support the automated finding" if hi <= 0.10 else "inconclusive")
    lines += ["", f"**Reading fixed in advance (protocol section 8):** {reading}.", "", "## E3 and E4. Agreement per ECG", "",
              "| Comparison | ECGs | κ LVOT call | κ QS-like PVC | r of the PVC, mean difference | 95% limits of agreement | Spearman |",
              "|---|---|---|---|---|---|---|"]
    for w in WHO:
        lines.append(f"| {w} against automated | " + versus(e, f"{w}_rp", f"{w}_call", f"{w}_qs", "auto_r_pvc", "auto_call", "auto_qs") + " |")
    lines.append("| reader 1 against reader 2 | " + versus(e, "reader1_rp", "reader1_call", "reader1_qs", "reader2_rp", "reader2_call", "reader2_qs") + " |")
    p1, p2 = tables["reader1"], tables["reader2"]
    common = p1.index.intersection(p2.index)
    x, y = p1.differ[common].to_numpy(bool), p2.differ[common].to_numpy(bool)
    lines += ["", f"Reader 1 against reader 2, pair-level changed call: {len(common)} pairs, κ {kappa(x, y):.2f}.", "",
              "## E5. Automated QS-like PVC on exactly one ECG (automated-discordant pairs)", ""]
    hits, n = 0, 0
    joint_ok = set(tables["joint"].index)
    for pair, g in e[e.stratum == "discordant"].sort_values("ecg").groupby("pair"):
        if pair in joint_ok and g.auto_qs.sum() == 1:
            n += 1
            hits += int(g.joint_qs.astype(bool).tolist() == g.auto_qs.tolist())
    lines.append(f"The joint reading also found a QS-like PVC on that ECG only in {hits} of {n} pairs" + (f" ({hits / n:.0%})." if n else "."))
    (docs / "wp3_readers_result.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["sample", "pages", "score"])
    ap.add_argument("--test", help="directory for a synthetic run; real data are not read")
    a = ap.parse_args()
    out, docs = (Path(a.test), Path(a.test)) if a.test else (OUT3 / "readers", DOCS)
    if a.step == "sample":
        synthetic(out) if a.test else sample(out, docs)
    elif a.step == "pages":
        pages(out)
    else:
        score(out, docs)


if __name__ == "__main__":
    main()
